CREATE TABLE Eleve (
    id INT NOT NULL AUTO_INCREMENT,
	name VARCHAR(64) CHARACTER SET utf8 COLLATE utf8_unicode_ci NOT NULL,
	UNIQUE KEY id (id) USING BTREE,
	PRIMARY KEY (id)
);

CREATE TABLE Tribu (
	id INT NOT NULL AUTO_INCREMENT,
	name VARCHAR(64) CHARACTER SET utf8 COLLATE utf8_unicode_ci NOT NULL,
    logo VARCHAR(128) CHARACTER SET utf8 COLLATE utf8_unicode_ci NOT NULL,
    coach INT,
    score INT NOT NULL DEFAULT 0,
	UNIQUE KEY id (id) USING BTREE,
	PRIMARY KEY (id),
    FOREIGN KEY (coach) REFERENCES Eleve(id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE Equipe (
	tribu INT NOT NULL,
    eleve INT NOT NULL,
    PRIMARY KEY (tribu, eleve),
    FOREIGN KEY (tribu) REFERENCES Tribu(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (eleve) REFERENCES Eleve(id) ON DELETE CASCADE ON UPDATE CASCADE
);